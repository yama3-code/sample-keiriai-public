/** 本文から「よくある疑問」の Q./A. を取り出す。 */
export function parseFaq(text: string) {
  const items: { q: string; a: string }[] = [];
  const blocks = text.split(/\n(?=Q\. )/).map((b) => b.trim()).filter((b) => b.startsWith("Q. "));
  for (const block of blocks) {
    const match = block.match(/^Q\. ([\s\S]+?)\nA\. ([\s\S]+)$/);
    if (match) items.push({ q: match[1].trim(), a: match[2].trim() });
  }
  return items;
}
