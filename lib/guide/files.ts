export function guideFilePlace(path: string, fallback: string): string {
  if (/\.(css|ico)$/.test(path)) return "表示用の素材";
  if (["components/guide/GuideArticle.tsx", "components/guide/ArchitectureDiagrams.tsx", "components/guide/ChapterFigures.tsx", "components/guide/Illustrations.tsx"].includes(path)) return "サーバー";
  if (["lib/master-excel.ts", "lib/run-stream.ts"].includes(path)) return "画面";
  if (/^lib\/(models|csv|upload-types|master-types|configuration-types|configuration-text|markdown-links)\.ts$/.test(path) || path.startsWith("lib/guide/")) return "共有の定義・処理";
  if (path.startsWith("lib/")) return "サーバー";
  return fallback;
}
export const guideFiles: GuideFile[] = guideFileGroups.flatMap((group) => group.files.map(([path, role]) => ({ path, role, place: guideFilePlace(path, group.place) })));
